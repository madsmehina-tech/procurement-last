"""Builds the three Word templates shipped with the system, on the company's OWN letterhead file:

    python contract_starters/make_starters.py [path-to-a-company-contract.docx]

* letterhead_base.docx  = the company's contract file (full-page letterhead in its header) with the body removed; made once from any contract of the company.
* then the three templates are written into it:  عقد مقاول من الباطن · عقد أعمال تركيب (عمالة وتركيب) · اتفاقية توريد.
The wording comes from the company's own contracts (the pump / fence / trailers contracts and عقد الصروح المتقنة); the specifics became marks.
Font: Sakkal Majalla 12, as in the company's contracts.
"""
