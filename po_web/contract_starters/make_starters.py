        cell.paragraphs[0]._p.getparent().remove(cell.paragraphs[0]._p)
        para(cell, head_t, size=HEAD, bold=True, underline=True, align="center", after=120)
        para(cell, who, bold=True, align="center", after=140)
        para(cell, "الاسم: " + rep, align="right", after=140)
        para(cell, "الصفة: " + ttl, align="right", after=140)
        para(cell, "التوقيع: ...........................................", align="right", after=140)
